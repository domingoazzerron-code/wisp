/**
 * Build-time service worker generator.
 * Reads dist/ after Vite build and writes dist/sw.js with a precache of
 * index.html, assets (hashed), and public shell files.
 *
 * Usage (from vite plugin or CLI):
 *   node tools/generate-sw.mjs
 *   node tools/generate-sw.mjs --out dist
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const outDir = process.argv.includes('--out')
  ? process.argv[process.argv.indexOf('--out') + 1]
  : 'dist';
const dist = join(ROOT, outDir);

const SHELL_FILES = [
  '/',
  '/manifest.json',
  '/icon-192.png',
  '/icon-512.png',
  '/icon-maskable-512.png',
  '/apple-touch-icon.png',
];

function walk(dir, base = dir) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) out.push(...walk(p, base));
    else out.push('/' + relative(base, p).split('\\').join('/'));
  }
  return out;
}

function buildSw(precache, version) {
  return `// Generated by tools/generate-sw.mjs — do not edit by hand.
// VERSION bumps when the precache set changes.
const VERSION = ${JSON.stringify(version)};
const SHELL = \`tracker-shell-\${VERSION}\`;
const FONTS = 'tracker-fonts';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(SHELL)
      .then((c) => c.addAll(PRECACHE))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) =>
        Promise.all(keys.filter((k) => k !== SHELL && k !== FONTS).map((k) => caches.delete(k)))
      )
      .then(() => self.clients.claim())
  );
});

function withTimeout(ms, p) {
  return new Promise((resolve, reject) => {
    const t = setTimeout(() => reject(new Error('timeout')), ms);
    p.then(
      (v) => { clearTimeout(t); resolve(v); },
      (err) => { clearTimeout(t); reject(err); },
    );
  });
}

async function staleWhileRevalidate(req, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(req);
  const refresh = fetch(req)
    .then((res) => {
      if (res && (res.ok || res.type === 'opaque')) cache.put(req, res.clone());
      return res;
    })
    .catch(() => null);
  return hit || (await refresh) || Response.error();
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  if (url.hostname === 'fonts.googleapis.com' || url.hostname === 'fonts.gstatic.com') {
    e.respondWith(staleWhileRevalidate(req, FONTS));
    return;
  }

  if (url.origin !== location.origin) return;
  if (url.pathname.startsWith('/api/')) return;

  // Navigations: network first (new deploys), fall back to cached shell.
  if (req.mode === 'navigate') {
    e.respondWith(
      withTimeout(3000, fetch(req))
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(SHELL).then((c) => c.put('/', copy));
          }
          return res;
        })
        .catch(() => caches.match('/').then((r) => r || Response.error())),
    );
    return;
  }

  // Hashed assets and other same-origin static files.
  e.respondWith(staleWhileRevalidate(req, SHELL));
});
`;
}

function main() {
  if (!existsSync(dist)) {
    console.error('dist/ not found — run vite build first');
    process.exit(1);
  }

  const assets = walk(dist)
    .filter((p) => !p.endsWith('/sw.js') && !p.endsWith('.map'))
    // index.html is served as /
    .map((p) => (p === '/index.html' ? '/' : p));

  const set = new Set([...SHELL_FILES, ...assets]);
  const precache = [...set].sort();

  const hash = createHash('sha1').update(precache.join('\n')).digest('hex').slice(0, 8);
  const version = 'v' + hash;

  const code = buildSw(precache, version);
  writeFileSync(join(dist, 'sw.js'), code);
  console.log('Wrote dist/sw.js VERSION=' + version + ' (' + precache.length + ' urls)');
}

main();
